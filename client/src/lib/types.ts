// client/src/lib/types.ts

// =====================================================
// SHARED
// =====================================================

export type UUID = string;

export type StockStatus = "in_stock" | "limited" | "out_of_stock";
export type OrderStatus = "pending" | "processing" | "shipped" | "delivered" | "cancelled";
export type DiscountType = "percentage" | "fixed";

// MySQL timestamps coming as string
export type Timestamp = string;

// =====================================================
// USERS
// =====================================================

export type UserProfile = {
  id: UUID;
  email: string;
  password_hash?: string; // never use in UI, but exists in DB
  first_name: string;
  last_name: string;
  phone: string;
  is_admin: boolean;
  created_at: Timestamp;
  updated_at: Timestamp;
};

export type UserAddress = {
  id: UUID;
  user_id: UUID;
  first_name: string;
  last_name: string;
  email: string;
  phone: string;
  address_line1: string;
  address_line2: string;
  town: string;
  postal_code: string;
  country: string;
  is_default: boolean;
  created_at: Timestamp;
};

// =====================================================
// PRODUCT CATEGORIES (product_categories + pivot)
// =====================================================

export type ProductCategory = {
  id: UUID;
  parent_id: UUID | null;
  name: string;
  slug: string;
  description: string | null;
  image_url: string | null;
  display_order: number;
  created_at: Timestamp;
  updated_at: Timestamp;
};

export type ProductImage = {
  id: UUID;
  product_id: UUID;
  image_url: string;
  alt_text: string | null;
  display_order: number;
  is_primary: boolean;
  created_at: Timestamp;
};

export type ProductReview = {
  id: UUID;
  product_id: UUID;
  customer_name: string;
  customer_email: string;
  rating: number; // 1..5
  title: string | null;
  comment: string | null;
  is_verified_purchase: boolean;
  helpful_count: number;
  created_at: Timestamp;
  updated_at: Timestamp;
};

export type Product = {
  id: UUID;
  name: string;
  slug: string;
  description: string | null;
  short_description: string | null;

  // DB is DECIMAL(10,2) so it may come as string depending on driver
  price: number | string;
  compare_at_price: number | string | null;

  image_url: string | null;

  stock_status: StockStatus;
  is_featured: boolean;
  is_new: boolean;

  ingredients: string | null;
  usage: string | null;
  suitability: string | null;
  formula_benefits: string | null;
  cure_duration: string | null;
  usage_advice: string | null;
  composition: string | null;
  precautions: string | null;

  // DB is JSON; API parses, but keep safe
  benefits: string[];

  average_rating: number | string;
  review_count: number;

  created_at: Timestamp;
  updated_at: Timestamp;

  // Relations (from API)
  categories?: ProductCategory[];
  images?: ProductImage[];
  reviews?: ProductReview[];
};

export type ProductCategoryPivot = {
  product_id: UUID;
  category_id: UUID;
};

// =====================================================
// BLOG (blog_posts + blog_categories + pivot)
