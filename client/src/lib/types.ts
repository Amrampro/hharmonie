export type BlogPostCategoryPivot = {
  blog_post_id: UUID;
  category_id: UUID;
};

// =====================================================
// ORDERS
// =====================================================

export type Order = {
  id: UUID;
  user_id: UUID | null;
  order_number: string | null; // generated by trigger, but column allows null
  status: OrderStatus;

  subtotal: number | string;
  discount_amount: number | string;
  total: number | string;

  coupon_id: UUID | null;

  shipping_first_name: string | null;
  shipping_last_name: string | null;
  shipping_email: string | null;
  shipping_phone: string | null;
  shipping_address_line1: string | null;
  shipping_address_line2: string | null;
  shipping_town: string | null;
  shipping_postal_code: string | null;
  shipping_country: string | null;

  notes: string | null;

  created_at: Timestamp;
  updated_at: Timestamp;
};

export type OrderItem = {
  id: UUID;
  order_id: UUID;
  product_id: UUID | null;
  product_name: string | null;
  product_price: number | string | null;
  quantity: number;
  subtotal: number | string | null;
  created_at: Timestamp;
};

// =====================================================
// COUPONS
// =====================================================

export type Coupon = {
  id: UUID;
  code: string;
  description: string;
  discount_type: DiscountType;
  discount_value: number | string;

  min_purchase_amount: number | string;
  max_discount_amount: number | string | null;

  valid_from: Timestamp;
  valid_until: Timestamp | null;

  usage_limit_per_user: number;
  total_usage_limit: number | null;
  current_usage_count: number;

  is_active: boolean;

  requires_first_order: boolean;
  requires_min_orders: number;

  created_at: Timestamp;
};

export type CouponUsage = {
  id: UUID;
  coupon_id: UUID | null;
  user_id: UUID | null;
  order_id: UUID | null;
  discount_applied: number | string | null;
  created_at: Timestamp;
};

